#' @section Data Type Vocabulary:
#' Where a page says which data types an argument takes, it names a group of
#' them with a single word:
#'
#' * *any data type* -- all of them: `bool`, the signed and unsigned integers,
#'   and the floats.
#' * *numeric* -- signed integer, unsigned integer and float.
#' * *integer* -- signed and unsigned integer.
#' * *integerish* -- boolean and integer, signed or unsigned.
#' * *signed numeric* -- signed integer and float.
#' * *float* -- `f32` and `f64`.
#' * *boolean* -- `bool`, the only member of its category.
#'
#' See [`dtypes`] for the categories these groups are built from and for the
#' default data type an R value commits to.
