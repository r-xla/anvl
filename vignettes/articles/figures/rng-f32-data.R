# Writes rng-f32-data.tex, the curves of rng-f32-cost.tex.
# Run from this directory: Rscript rng-f32-data.R

coords <- function(x, y) paste0("(", signif(x, 6L), ",", signif(y, 6L), ")", collapse = " ")

# Expected fraction of n i.i.d. draws from m equally likely values that repeat
# an earlier draw: (n - E[number of distinct values]) / n.
repeat_fraction <- function(n, m) (n + m * expm1(n * log1p(-1 / m))) / n

n <- 10^seq(3, 8, length.out = 51L)
ties <- vapply(
  c(single = 2^23, baseR = 2^32, double = 2^52),
  function(m) coords(n, repeat_fraction(n, m)),
  character(1L)
)

# An f32 Box-Muller normal is R cos(theta) with radius
# R = sqrt(-2 log(k 2^-23)), k = 1, ..., 2^23, each with probability 2^-23.
# Only small k reach the tail; theta is treated as continuous.
radius <- sqrt(-2 * log(seq_len(20000L) / 2^23))
tail_f32 <- function(x) sum(2 / pi * acos(x / radius[radius > x])) / 2^23
x <- seq(4, 6.8, by = 0.01)
ratio <- vapply(x, tail_f32, numeric(1L)) / (2 * pnorm(-x))

writeLines(
  c(
    "% generated by rng-f32-data.R",
    sprintf("\\def\\dup%s{%s}", names(ties), ties),
    sprintf("\\def\\tailratio{%s}", coords(x, ratio))
  ),
  "rng-f32-data.tex"
)
